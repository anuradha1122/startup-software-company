import { Head, router } from '@inertiajs/react';

type Generator = {
    name: string;
} | null;

type ReportRun = {
    public_id: string;
    report_type: string;
    format: string;
    status: string;
    download_name: string | null;
    row_count: number | null;
    failure_message: string | null;
    generated_at: string;
    generator: Generator;
};

type PaginationLink = {
    url: string | null;
    label: string;
    active: boolean;
};

type PaginatedRuns = {
    data: ReportRun[];
    links: PaginationLink[];
    total: number;
};

type Props = {
    runs: PaginatedRuns;
    filters: {
        report_type?: string | null;
        status?: string | null;
    };
};

export default function ReportRuns({ runs, filters }: Props) {
    return (
        <>
            <Head title="Report History" />

            <div className="space-y-6 p-6">
                <div className="flex flex-wrap justify-between gap-3">
                    <div>
                        <h1 className="text-2xl font-semibold">
                            Report History
                        </h1>

                        <p className="text-sm text-muted-foreground">
                            Audit history for M13 generated reports.
                        </p>
                    </div>

                    <div className="flex gap-2">
                        <a
                            href="/admin/reports/runs/export/excel"
                            className="rounded border px-3 py-2"
                        >
                            Excel
                        </a>

                        <a
                            href="/admin/reports/runs/export/pdf"
                            className="rounded border px-3 py-2"
                        >
                            PDF
                        </a>
                    </div>
                </div>

                <form
                    className="grid gap-3 rounded border p-4 md:grid-cols-3"
                    onSubmit={(event) => {
                        event.preventDefault();

                        const form = new FormData(event.currentTarget);

                        router.get(
                            '/admin/reports/runs',
                            Object.fromEntries(form.entries()),
                            {
                                preserveState: true,
                                preserveScroll: true,
                            },
                        );
                    }}
                >
                    <input
                        name="report_type"
                        placeholder="Report type"
                        defaultValue={filters.report_type ?? ''}
                        className="rounded border p-2"
                    />

                    <select
                        name="status"
                        defaultValue={filters.status ?? ''}
                        className="rounded border p-2"
                    >
                        <option value="">All statuses</option>

                        <option value="completed">Completed</option>

                        <option value="failed">Failed</option>
                    </select>

                    <button className="rounded border px-4 py-2">Filter</button>
                </form>

                <div className="overflow-x-auto rounded border">
                    <table className="w-full text-sm">
                        <thead className="bg-muted">
                            <tr>
                                <th className="p-3 text-left">Report</th>

                                <th className="p-3 text-left">Format</th>

                                <th className="p-3 text-left">Status</th>

                                <th className="p-3 text-left">Rows</th>

                                <th className="p-3 text-left">Generated By</th>

                                <th className="p-3 text-left">Generated At</th>

                                <th className="p-3 text-left">Failure</th>
                            </tr>
                        </thead>

                        <tbody>
                            {runs.data.map((run) => (
                                <tr key={run.public_id} className="border-t">
                                    <td className="p-3">{run.report_type}</td>

                                    <td className="p-3">{run.format}</td>

                                    <td className="p-3">{run.status}</td>

                                    <td className="p-3">
                                        {run.row_count ?? '-'}
                                    </td>

                                    <td className="p-3">
                                        {run.generator?.name ?? '-'}
                                    </td>

                                    <td className="p-3">{run.generated_at}</td>

                                    <td className="max-w-sm p-3">
                                        {run.failure_message ?? '-'}
                                    </td>
                                </tr>
                            ))}
                        </tbody>
                    </table>
                </div>
            </div>
        </>
    );
}
